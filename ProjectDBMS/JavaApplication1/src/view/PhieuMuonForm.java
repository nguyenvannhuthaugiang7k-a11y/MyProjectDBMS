    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblPhieuMuon.getModel();
        model.setRowCount(0);

        String sql;

        if (vaiTro.equalsIgnoreCase("ADMIN")) {
            sql = "SELECT MaPM, MaTK, MaSach, NgayMuon, HanTra, NgayTra, TrangThai "
                + "FROM PhieuMuon ORDER BY MaPM DESC";
        } else {
            sql = "SELECT MaPM, MaTK, MaSach, NgayMuon, HanTra, NgayTra, TrangThai "
                + "FROM PhieuMuon WHERE MaTK = ? ORDER BY MaPM DESC";
        }

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            if (!vaiTro.equalsIgnoreCase("ADMIN")) {
                ps.setInt(1, maTK);
            }

            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("MaPM"),
                        rs.getInt("MaTK"),
                        rs.getInt("MaSach"),
                        rs.getDate("NgayMuon"),
                        rs.getDate("HanTra"),
                        rs.getDate("NgayTra"),
                        rs.getString("TrangThai")
                    });
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Lỗi tải danh sách phiếu mượn: " + e.getMessage());
        }
    }

