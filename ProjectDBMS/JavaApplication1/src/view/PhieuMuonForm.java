    private void btnMuonSachActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMuonSachActionPerformed
        // TODO add your handling code here:
        String maTKText = txtMaTK.getText().trim();
        String maSachText = txtMaSach.getText().trim();
        String hanTraText = txtHanTra.getText().trim();

        // Kiem tra du lieu nhap
        if (maTKText.isEmpty() || maSachText.isEmpty()
                || hanTraText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Vui long nhap ma tai khoan, ma sach va han tra!"
            );
            return;
        }

        try {
            int maTK = Integer.parseInt(maTKText);
            int maSach = Integer.parseInt(maSachText);

            // Chuyen chuoi ngay thanh LocalDate
            LocalDate hanTra = LocalDate.parse(hanTraText);
            LocalDate ngayHienTai = LocalDate.now();

            // Kiem tra han tra
            if (hanTra.isBefore(ngayHienTai)) {
                JOptionPane.showMessageDialog(
                        this,
                        "Han tra khong duoc nho hon ngay muon!"
                );
                return;
            }

            String sql = "{CALL sp_MuonSach(?, ?, ?)}";

            try (Connection conn = DBConnection.getConnection();
                 CallableStatement cs = conn.prepareCall(sql)) {

                cs.setInt(1, maTK);
                cs.setInt(2, maSach);
                cs.setDate(3, Date.valueOf(hanTra));

                cs.execute();

                JOptionPane.showMessageDialog(
                        this,
                        "Muon sach thanh cong!"
                );

                loadData();

                txtMaTK.setText("");
                txtMaSach.setText("");
                txtHanTra.setText("");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ma tai khoan va ma sach phai la so nguyen!"
            );

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ngay khong hop le! Vui long nhap theo dang yyyy-MM-dd."
            );

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Loi muon sach: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnMuonSachActionPerformed

    private void tblPhieuMuonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPhieuMuonMouseClicked
        // TODO add your handling code here:
        int row = tblPhieuMuon.getSelectedRow();

        if (row >= 0) {
            txtMaPM.setText(tblPhieuMuon.getValueAt(row, 0).toString());
            txtMaTK.setText(tblPhieuMuon.getValueAt(row, 1).toString());
            txtMaSach.setText(tblPhieuMuon.getValueAt(row, 2).toString());

            txtNgayMuon.setText(
                tblPhieuMuon.getValueAt(row, 3).toString()
            );

            txtHanTra.setText(
                tblPhieuMuon.getValueAt(row, 4).toString()
            );

            Object ngayTra = tblPhieuMuon.getValueAt(row, 5);
            txtNgayTra.setText(ngayTra == null ? "" : ngayTra.toString());

            txtTrangThai.setText(
                tblPhieuMuon.getValueAt(row, 6).toString()
            );
            
            String trangThai = tblPhieuMuon.getValueAt(row, 6).toString();

            if (trangThai.equalsIgnoreCase("DA_TRA")) {
                int maPM = Integer.parseInt(
                    tblPhieuMuon.getValueAt(row, 0).toString()
                );

                double tienPhat = tinhTienPhat(maPM);

                txtTienPhat.setText(
                    String.format("%,.0f", tienPhat)
                );
            } else {
                txtTienPhat.setText("Chưa trả sách");
            }
        }
    }//GEN-LAST:event_tblPhieuMuonMouseClicked

