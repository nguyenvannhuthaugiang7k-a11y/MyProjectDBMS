    private void btnDangNhapActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDangNhapActionPerformed
        // TODO add your handling code here:
        String tenTK = txtTenTK.getText().trim();
        String matKhau = txtMatKhau.getText();

        // Kiem tra du lieu nhap
        if (tenTK.isEmpty() || matKhau.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Vui long nhap day du ten tai khoan va mat khau!");
            return;
        }

        String sql = "SELECT MaTK, TenTK, HoTen, VaiTro "
                   + "FROM TaiKhoan "
                   + "WHERE TenTK = ? AND MatKhau = ?";

        try (Connection conn = DBConnection.getConnection()) {

            if (conn == null) {
                JOptionPane.showMessageDialog(this,
                        "Khong the ket noi den co so du lieu!");
                return;
            }

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setString(1, tenTK);
                ps.setString(2, matKhau);

                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        int maTK = rs.getInt("MaTK");
                        String hoTen = rs.getString("HoTen");
                        String vaiTro = rs.getString("VaiTro");

                        JOptionPane.showMessageDialog(this,
                                "Dang nhap thanh cong!");
                        
                        MainForm mainForm = new MainForm(maTK, hoTen, vaiTro);
                        mainForm.setLocationRelativeTo(null);
                        mainForm.setVisible(true);

                        this.dispose();
                    } else {
                        JOptionPane.showMessageDialog(this,
                                "Ten tai khoan hoac mat khau khong dung!");
                    }
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Loi truy van co so du lieu: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDangNhapActionPerformed

