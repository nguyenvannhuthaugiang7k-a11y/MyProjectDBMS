    private void loadData() {
        DefaultTableModel model =
            (DefaultTableModel) tblTaiKhoan.getModel();

        model.setRowCount(0);

        String sql = "SELECT MaTK, TenTK, HoTen, VaiTro "
                   + "FROM TaiKhoan ORDER BY MaTK";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("MaTK"),
                    rs.getString("TenTK"),
                    rs.getString("HoTen"),
                    rs.getString("VaiTro")
                });
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Lỗi tải danh sách tài khoản: " + e.getMessage());
        }
    }
    
    private void timKiemTaiKhoan() {
        DefaultTableModel model =
                (DefaultTableModel) tblTaiKhoan.getModel();

            model.setRowCount(0);

        String tuKhoa = txtTimKiem.getText().trim();

        String sql = "SELECT MaTK, TenTK, HoTen, VaiTro "
                   + "FROM TaiKhoan "
                   + "WHERE TenTK LIKE ? "
                   + "ORDER BY MaTK";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, "%" + tuKhoa + "%");

            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("MaTK"),
                        rs.getString("TenTK"),
                        rs.getString("HoTen"),
                        rs.getString("VaiTro")
                    });
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Lỗi tìm kiếm tài khoản: " + e.getMessage()
            );
        }
    }
    
