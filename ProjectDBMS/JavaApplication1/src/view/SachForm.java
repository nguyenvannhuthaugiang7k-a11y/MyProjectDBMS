    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed
        // TODO add your handling code here:
        String tuKhoa = txtTimKiem.getText().trim();

        if (tuKhoa.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui long nhap ma sach hoac ten sach can tim!");
            return;
        }

        String sql = "SELECT MaSach, TenSach, TacGia, TheLoai, SoLuong, SoLuongCon "
                   + "FROM Sach "
                   + "WHERE CAST(MaSach AS CHAR) LIKE ? OR TenSach LIKE ? "
                   + "ORDER BY MaSach";

        try (Connection conn = DBConnection.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, "%" + tuKhoa + "%");
            ps.setString(2, "%" + tuKhoa + "%");

            try (ResultSet rs = ps.executeQuery()) {
                DefaultTableModel model = (DefaultTableModel) tblSach.getModel();
                model.setRowCount(0);

                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("MaSach"),
                        rs.getString("TenSach"),
                        rs.getString("TacGia"),
                        rs.getString("TheLoai"),
                        rs.getInt("SoLuong"),
                        rs.getInt("SoLuongCon")
                    });
                }

                if (model.getRowCount() == 0) {
                    JOptionPane.showMessageDialog(this, "Khong tim thay sach phu hop!");
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Loi tim kiem sach: " + e.getMessage());
        }
    }//GEN-LAST:event_btnTimKiemActionPerformed

