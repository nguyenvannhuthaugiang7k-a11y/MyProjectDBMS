    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:
        String tenSach = txtTenSach.getText().trim();
        String tacGia = txtTacGia.getText().trim();
        String theLoai = txtTheLoai.getText().trim();

        String soLuongText = txtSoLuong.getText().trim();
        String soLuongConText = txtSoLuongCon.getText().trim();

        // Kiem tra du lieu trong
        if (tenSach.isEmpty() || tacGia.isEmpty()
                || theLoai.isEmpty() || soLuongText.isEmpty()
                || soLuongConText.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Vui long nhap day du thong tin sach!");
            return;
        }

        try {
            int soLuong = Integer.parseInt(soLuongText);
            int soLuongCon = Integer.parseInt(soLuongConText);

            if (soLuong < 0 || soLuongCon < 0
                    || soLuongCon > soLuong) {
                JOptionPane.showMessageDialog(this,
                        "So luong khong hop le!");
                return;
            }

            String sql = "INSERT INTO Sach "
                    + "(TenSach, TacGia, TheLoai, SoLuong, SoLuongCon) "
                    + "VALUES (?, ?, ?, ?, ?)";

            try (Connection conn = DBConnection.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sql)) {

                ps.setString(1, tenSach);
                ps.setString(2, tacGia);
                ps.setString(3, theLoai);
                ps.setInt(4, soLuong);
                ps.setInt(5, soLuongCon);

                ps.executeUpdate();

                JOptionPane.showMessageDialog(this,
                        "Them sach thanh cong!");

                loadData();

                txtMaSach.setText("");
                txtTenSach.setText("");
                txtTacGia.setText("");
                txtTheLoai.setText("");
                txtSoLuong.setText("");
                txtSoLuongCon.setText("");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "So luong phai la so nguyen!");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Loi them sach: " + e.getMessage());
        }
    }//GEN-LAST:event_btnThemActionPerformed

