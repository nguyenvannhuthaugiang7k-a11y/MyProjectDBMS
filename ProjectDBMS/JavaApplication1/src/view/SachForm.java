    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        String maSachText = txtMaSach.getText().trim();

        if (maSachText.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Vui long chon sach can xoa!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this,
                "Ban co chac chan muon xoa sach nay?",
                "Xac nhan xoa",
                JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            int maSach = Integer.parseInt(maSachText);

            String sql = "DELETE FROM Sach WHERE MaSach = ?";

            try (Connection conn = DBConnection.getConnection();
                 PreparedStatement ps = conn.prepareStatement(sql)) {

                ps.setInt(1, maSach);

                int result = ps.executeUpdate();

                if (result > 0) {
                    JOptionPane.showMessageDialog(this,
                            "Xoa sach thanh cong!");

                    loadData();

                    txtMaSach.setText("");
                    txtTenSach.setText("");
                    txtTacGia.setText("");
                    txtTheLoai.setText("");
                    txtSoLuong.setText("");
                    txtSoLuongCon.setText("");
                } else {
                    JOptionPane.showMessageDialog(this,
                            "Khong tim thay sach can xoa!");
                }
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ma sach khong hop le!");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Loi xoa sach: " + e.getMessage());
        }
    }//GEN-LAST:event_btnXoaActionPerformed

